// Buttons

bool UPI_BTN_ACT_PRESSED()
{
  return PIN_read(PIN_BTN_ACT1) || PIN_read(PIN_BTN_ACT2);
}

bool UPI_BTN_ACT_RELEASED()
{
  return !PIN_read(PIN_BTN_ACT1) && !PIN_read(PIN_BTN_ACT2);
}

bool UPI_BTN_DIR_PRESSED()
{
  return false; // аналоговый джойстик в этой ревизии не используется
}

bool UPI_BTN_DIR_RELEASED()
{
  return true;  // аналоговый джойстик в этой ревизии не используется
}

#define UPI_BTN_ALL_RELEASED()        (UPI_BTN_ACT_RELEASED() && UPI_BTN_DIR_RELEASED())

