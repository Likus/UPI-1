// Init driver
static inline void UPI_START(void) {
  PIN_output(PIN_BEEP);
  PIN_high(PIN_BEEP);

  DLY_ms(500);
  PIN_low(PIN_BEEP);

  OLED_init();

  draw_bitmap(0,0,128,64,Logo,0);
  draw_update();

  UPI_SOUND_PLAY(32, 255);
  UPI_SOUND_PLAY(32, 255);
  UPI_SOUND_PLAY(64, 255);
  UPI_SOUND_PLAY(64, 255);
  UPI_SOUND_PLAY(48, 255);
  UPI_SOUND_PLAY(48, 255);

  DLY_ms(1000);

  draw_init();
}

